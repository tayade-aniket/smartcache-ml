"""
LLM Provider Abstraction for SmartCache ML.
Supports deterministic offline MockProvider and optional local OllamaProvider.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass
import time
import requests
from typing import Optional, Dict, Any


@dataclass
class LLMResponse:
    text: str
    model_name: str
    input_tokens: int
    output_tokens: int
    latency_seconds: float
    is_mock: bool = True
    metadata: Optional[Dict[str, Any]] = None


class BaseLLMProvider(ABC):
    """Abstract interface for LLM inference providers."""

    @abstractmethod
    def generate(self, prompt: str, model_type: str = "small") -> LLMResponse:
        """
        Generate a text response for the given prompt.
        
        Args:
            prompt: User input prompt
            model_type: 'small' or 'large'
        """
        pass


class MockProvider(BaseLLMProvider):
    """
    Deterministic, offline mock provider.
    Zero external dependencies, fast execution, predictable token counts.
    Never pretends to be a real LLM.
    """

    def __init__(self, canned_answers: Optional[Dict[str, str]] = None):
        self.canned_answers = canned_answers or {}
        # Simple token estimation heuristic: ~4 characters per token
        self.chars_per_token = 4

    def _estimate_tokens(self, text: str) -> int:
        return max(1, len(text) // self.chars_per_token)

    def generate(self, prompt: str, model_type: str = "small") -> LLMResponse:
        start_time = time.perf_counter()

        # Check canned dictionary first
        normalized = prompt.strip().lower()
        matched_answer = None
        for key, ans in self.canned_answers.items():
            if key.lower() in normalized or normalized in key.lower():
                matched_answer = ans
                break

        if matched_answer:
            response_text = matched_answer
        else:
            # Deterministic template response
            prefix = "[MOCK-SMALL]" if model_type == "small" else "[MOCK-LARGE]"
            response_text = (
                f"{prefix} Deterministic response for query: '{prompt}'. "
                f"Generated by SmartCache MockProvider for educational benchmarking."
            )

        # Simulate small compute delay
        simulated_delay = 0.015 if model_type == "small" else 0.040
        time.sleep(simulated_delay)

        latency = time.perf_counter() - start_time
        input_tokens = self._estimate_tokens(prompt)
        output_tokens = self._estimate_tokens(response_text)

        model_name = "mock-small-v1" if model_type == "small" else "mock-large-v1"

        return LLMResponse(
            text=response_text,
            model_name=model_name,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            latency_seconds=latency,
            is_mock=True,
            metadata={"simulated_delay": simulated_delay}
        )


class OllamaProvider(BaseLLMProvider):
    """
    Local Ollama inference provider.
    Connects to local Ollama daemon (e.g. http://localhost:11434).
    """

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        small_model: str = "llama3.2:1b",
        large_model: str = "llama3.2:3b",
        timeout_seconds: float = 30.0
    ):
        self.base_url = base_url.rstrip("/")
        self.small_model = small_model
        self.large_model = large_model
        self.timeout = timeout_seconds

    def check_health(self) -> bool:
        try:
            r = requests.get(f"{self.base_url}/api/tags", timeout=2.0)
            return r.status_code == 200
        except Exception:
            return False

    def generate(self, prompt: str, model_type: str = "small") -> LLMResponse:
        model_name = self.small_model if model_type == "small" else self.large_model
        endpoint = f"{self.base_url}/api/generate"

        payload = {
            "model": model_name,
            "prompt": prompt,
            "stream": False,
        }

        start_time = time.perf_counter()
        try:
            resp = requests.post(endpoint, json=payload, timeout=self.timeout)
            resp.raise_for_status()
            data = resp.json()

            latency = time.perf_counter() - start_time
            response_text = data.get("response", "")
            input_tokens = data.get("prompt_eval_count", max(1, len(prompt) // 4))
            output_tokens = data.get("eval_count", max(1, len(response_text) // 4))

            return LLMResponse(
                text=response_text,
                model_name=model_name,
                input_tokens=input_tokens,
                output_tokens=output_tokens,
                latency_seconds=latency,
                is_mock=False,
                metadata={"total_duration": data.get("total_duration")}
            )
        except requests.exceptions.RequestException as e:
            # Fall back to structured error or propagate
            raise ConnectionError(
                f"Failed to connect to Ollama at {self.base_url} for model '{model_name}': {e}"
            )


def get_llm_provider(
    provider_type: str = "mock",
    canned_answers: Optional[Dict[str, str]] = None,
    base_url: str = "http://localhost:11434",
    small_model: str = "llama3.2:1b",
    large_model: str = "llama3.2:3b"
) -> BaseLLMProvider:
    """Provider factory."""
    if provider_type.lower() == "ollama":
        provider = OllamaProvider(
            base_url=base_url,
            small_model=small_model,
            large_model=large_model
        )
        if provider.check_health():
            return provider
        print("Warning: Ollama is unreachable. Falling back to MockProvider.")

    return MockProvider(canned_answers=canned_answers)
